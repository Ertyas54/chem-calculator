// ============================================================
// Нормировка всех значений K и R.
// Каждая переменная приводится к диапазону [0, 1] делением
// на свой максимум.
// ============================================================

// ------------------------------------------------------------
// Максимумы для каждой переменной (для нормировки)
// ------------------------------------------------------------
export const K_MAX = {
  K1: 48,
  K2: 120,
  K3: 30,
  K4: 12,
  K5: 200,
  K6: 300,
  K7: 500,
  K8: 200,
  K9: 100,
  K10: 500,
  K11: 300,
  K12: 100,
  K13: 5000,
  K14: 500,
  K15: 10,
}

export const R_MAX = {
  R1: 2,
  R2: 2,
  R3: 2,
  R4: 1,
}

// ------------------------------------------------------------
// Минимумы (обычно 0, но на всякий случай)
// ------------------------------------------------------------
export const K_MIN = {
  K1: 0, K2: 0, K3: 0, K4: 0, K5: 0, K6: 0,
  K7: 0, K8: 0, K9: 0, K10: 0, K11: 0, K12: 0,
  K13: 0, K14: 0, K15: 0,
}

export const R_MIN = {
  R1: 0, R2: 0, R3: 0, R4: 0,
}

// ------------------------------------------------------------
// Получить максимум переменной по её имени
// ------------------------------------------------------------
export function getMax(name) {
  if (name.startsWith('R')) return R_MAX[name] ?? 1
  return K_MAX[name] ?? 1
}

export function getMin(name) {
  if (name.startsWith('R')) return R_MIN[name] ?? 0
  return K_MIN[name] ?? 0
}

// ------------------------------------------------------------
// Нормировать одно значение в [0, 1]
// ------------------------------------------------------------
export function normalize(name, value) {
  const max = getMax(name)
  const min = getMin(name)
  if (max === min) return 0
  return (value - min) / (max - min)
}

// ------------------------------------------------------------
// Денормировать обратно (из [0, 1] в реальные единицы)
// ------------------------------------------------------------
export function denormalize(name, value) {
  const max = getMax(name)
  const min = getMin(name)
  return min + value * (max - min)
}

// ------------------------------------------------------------
// Нормировать все значения сразу
// ------------------------------------------------------------
export function normalizeAll(values) {
  const result = {}
  Object.entries(values).forEach(([name, value]) => {
    result[name] = normalize(name, value)
  })
  return result
}